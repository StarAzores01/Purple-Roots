function ube_source_products() {
    global $ube_regions;
    $products = [];
    foreach ($ube_regions as $area) {
        $primaryProduct = $area['products'][0] ?? 'Philippine Ube';
        $products[] = [
            'id' => $area['id'],
            'product_name' => $primaryProduct . ' - ' . $area['province'],
            'category' => $area['category'],
            'province' => $area['province'],
            'city' => $area['city'],
            'farmer_name' => implode(', ', array_slice($area['farmer_groups'], 0, 2)),
            'price' => $area['price'],
            'status' => $area['status'],
            'harvest_date' => $area['harvest_date'],
            'batch_code' => $area['batch_code'],
            'description' => $area['description'],
            'icon' => $area['icon'],
            'thumbnail' => $area['thumbnail'] ?? ''
        ];
    }
    return $products;
}

function find_ube_area($provinceOrCode) {
    global $ube_regions;
    foreach ($ube_regions as $area) {
        if (strcasecmp($area['province'], (string)$provinceOrCode) === 0 || strcasecmp($area['batch_code'], (string)$provinceOrCode) === 0 || (string)$area['id'] === (string)$provinceOrCode) {
            return $area;
        }
    }
    return null;
}


function ube_source_reach_url($area) {
    if (!empty($area['contact']['url'])) return $area['contact']['url'];
    $province = $area['province'] ?? 'Philippines';
    $region = $area['region'] ?? '';
    $query = $province . ' Provincial Agriculture Office official page ' . $region;
    return 'https://www.google.com/search?q=' . urlencode($query);
}

function ube_seller_reach_url($seller) {
    if (!empty($seller['official_url'])) return $seller['official_url'];
    $query = ($seller['name'] ?? 'ube seller Philippines') . ' official Facebook page Messenger website';
    return 'https://www.google.com/search?q=' . urlencode($query);
}

function ube_qr_url($text, $size = 180) {
    return 'https://api.qrserver.com/v1/create-qr-code/?size=' . intval($size) . 'x' . intval($size) . '&data=' . urlencode($text);
}

function ube_barcode_bars($text) {
    $hash = md5($text);
    $bars = [];
    for ($i = 0; $i < strlen($hash); $i++) {
        $bars[] = (hexdec($hash[$i]) % 4) + 1;
    }
    return $bars;
}
